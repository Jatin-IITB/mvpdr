"""Agentic diagnostic pipeline with LLM-powered reasoning.

Chains MVPDR+ classification, severity estimation, and knowledge base
retrieval through an LLM agent that reasons about the diagnosis and
produces structured reports.

Backends (in priority order):
1. **Ollama** (default) — local, free, runs Qwen 3 8B or any model
   with tool-calling support.  No API key needed.
2. **Anthropic** — cloud-based Claude, requires ``ANTHROPIC_API_KEY``.
3. **Rule-based** — deterministic fallback, no LLM dependency.

Set ``MVPDR_AGENT_BACKEND`` to ``ollama``, ``anthropic``, or ``rule``
to force a specific backend.
"""

import json
import os
from dataclasses import asdict, dataclass, field
from typing import Optional

from mvpdr.knowledge import DiseaseKnowledgeBase
from mvpdr.severity import SEVERITY_LABELS, SeverityLevel, SeverityResult


# -----------------------------------------------------------------------
# Structured report schema
# -----------------------------------------------------------------------

@dataclass
class DifferentialDiagnosis:
    disease_name: str
    confidence: float
    reasoning: str


@dataclass
class TreatmentRecommendation:
    immediate: list[str]
    long_term: list[str]
    organic_alternatives: list[str]


@dataclass
class DiagnosticReport:
    disease_name: str
    confidence: float
    severity_level: str
    severity_score: float
    affected_area_percent: float
    treatment: TreatmentRecommendation
    differential_diagnosis: list[DifferentialDiagnosis]
    reasoning_chain: list[str]
    caveats: list[str]
    mode: str  # "ollama", "anthropic", or "rule_based"

    def to_dict(self) -> dict:
        return asdict(self)

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent)

    def to_markdown(self) -> str:
        md = []
        md.append("# Plant Disease Diagnostic Report")
        md.append("")
        md.append(f"**Diagnosis:** {self.disease_name}")
        md.append(f"**Confidence:** {self.confidence:.1%}")
        md.append(f"**Severity:** {self.severity_level} (score: {self.severity_score:.2f})")
        md.append(f"**Affected Area:** {self.affected_area_percent:.1f}%")
        md.append("")

        md.append("## Reasoning")
        for i, step in enumerate(self.reasoning_chain, 1):
            md.append(f"{i}. {step}")
        md.append("")

        md.append("## Treatment Plan")
        if self.treatment.immediate:
            md.append("### Immediate Actions")
            for t in self.treatment.immediate:
                md.append(f"- {t}")
        if self.treatment.long_term:
            md.append("### Long-term Management")
            for t in self.treatment.long_term:
                md.append(f"- {t}")
        if self.treatment.organic_alternatives:
            md.append("### Organic Alternatives")
            for t in self.treatment.organic_alternatives:
                md.append(f"- {t}")
        md.append("")

        if self.differential_diagnosis:
            md.append("## Differential Diagnosis")
            for dd in self.differential_diagnosis:
                md.append(f"- **{dd.disease_name}** ({dd.confidence:.1%}): {dd.reasoning}")
            md.append("")

        if self.caveats:
            md.append("## Important Caveats")
            for c in self.caveats:
                md.append(f"- {c}")
            md.append("")

        md.append(f"---\n*Generated by MVPDR+ Diagnostic Agent ({self.mode} mode)*")
        return "\n".join(md)


